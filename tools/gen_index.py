MARKER = "<!-- generated by tools/gen_index.py -- do not edit manually -->"

# Above this many records in one folder, the generator suggests a split - together with the
# evidence needed to decide it. The rule: split only by a field that is single-valued for
# EVERY record in the folder. `allocated_to` is many-to-many for hardware requirements, so a
# split by component would force an arbitrary filing decision per record.
SPLIT_THRESHOLD = 40

# Grouped sections are only worth printing when they actually group something.
GROUP_MIN_RECORDS = 5
GROUP_MIN_BUCKETS = 2
# A grouping that puts almost everything into one bucket does not group anything - it only
# adds noise. Suppress it when the largest bucket holds this share or more.
GROUP_MAX_DOMINANCE = 0.8

SKIP_DIRS = {".git", ".github", ".claude", "node_modules", "__pycache__", "exports"}

