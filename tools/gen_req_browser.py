def parse_mapping(root: Path) -> list[dict]:
    """Read the process-area table from 09_process/aspice_mapping.md.

    The mapping is committed data on purpose: which process area a work product belongs to
    is a reviewable statement, not something this script should decide.
    """
    path = root / MAPPING_REL
    if not path.is_file():
        print(f"  ! {MAPPING_REL} not found - process views will be empty", file=sys.stderr)
        return []

    areas: list[dict] = []
    in_table = False
    for line in path.read_text(encoding="utf-8").split("\n"):
        line = line.strip()
        if not line.startswith("|"):
            in_table = False
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) != 7:
            continue
        if cells[0] == "Area":
            in_table = True
            continue
        if re.match(r"^[\s:\-]+$", cells[0]):
            continue
        if not in_table:
            continue

        def split(v: str) -> list[str]:
            return [] if v == "-" else [x.strip() for x in v.split(",") if x.strip()]

        areas.append({
            "id": cells[0],
            "framework": cells[1],
            "name": cells[2],
            "level": cells[3],
            "side": cells[4],
            "rec_src": split(cells[5]),
            "doc_src": split(cells[6]),
        })
    return areas


def resolve_areas(areas: list[dict], items: dict, root: Path) -> list[dict]:
    """Attach the concrete records and documents each area owns."""
    for area in areas:
        ids: list[str] = []
        for src in area["rec_src"]:
            if src.startswith("path:"):
                folder = src[5:]
                ids += [i for i, r in items.items() if r["file"].startswith(folder + "/")]
            elif src.startswith("id:"):
                ids += [i for i in items if i.startswith(src[3:])]
        area["ids"] = sorted(set(ids), key=sort_key)

        docs = []
        for d in area["doc_src"]:
            docs.append({"path": d, "exists": (root / d).exists()})
        area["docs"] = docs
        area["empty"] = not area["ids"] and not docs
    return areas


# ------------------------------------------------------------------- diagrams


def render_puml(src: str, label: str) -> str:
    """Render one PlantUML source to base64 SVG; empty string when it cannot be rendered."""
    if not shutil.which("plantuml"):
        return ""
    try:
        res = subprocess.run(
            ["plantuml", "-tsvg", "-pipe"],
            input=src.encode("utf-8"),
            capture_output=True,
            timeout=120,
        )
        if res.returncode == 0 and res.stdout.lstrip()[:4] in (b"<svg", b"<?xm"):
            return base64.b64encode(res.stdout).decode("ascii")
        err = res.stderr.decode("utf-8", "replace").strip()
        print(f"  ! {label}: PlantUML returned {res.returncode} {err[:200]}", file=sys.stderr)
    except (OSError, subprocess.SubprocessError) as exc:
        print(f"  ! {label}: {exc}", file=sys.stderr)
    return ""


def render_diagrams(root: Path) -> tuple[list[dict], bool]:
    """Render every PlantUML source to SVG. Returns (diagrams, plantuml_available)."""
    puml_dir = root / PUML_DIR
    if not puml_dir.is_dir():
        return [], True

    available = shutil.which("plantuml") is not None
    diagrams: list[dict] = []

    for path in sorted(puml_dir.glob("*.puml")):
        src = path.read_text(encoding="utf-8")
        title = ""
        for line in src.split("\n"):
            if line.strip().startswith("title "):
                title = line.strip()[6:].strip()
                break

        svg = render_puml(src, path.name) if available else ""

        diagrams.append(
            {
                "name": path.stem,
                "title": title or path.stem,
                "file": str(path.relative_to(root)),
                "svg": svg,
                "src": src,
            }
        )

    return diagrams, available


# ------------------------------------------------------------------- documents


def doc_title(root: Path, rel: str, fallback: str) -> str:
    """Prefer the document's own H1 over a title supplied by the mapping."""
    path = root / rel
    if path.suffix == ".md" and path.is_file():
        for line in path.read_text(encoding="utf-8").split("\n")[:40]:
            if line.startswith("# "):
                return line[2:].strip()
    return fallback


def collect_documents(root: Path, areas: list[dict]) -> list[dict]:
    """Every narrative work product reachable from the mapping or the fixed list."""
    wanted: dict[str, str] = {}
    for rel, title in DOCUMENTS:
        wanted.setdefault(rel, title)
    for area in areas:
        for rel in area["doc_src"]:
            wanted.setdefault(rel, Path(rel).stem.replace("_", " ").capitalize())

    embedded = {rel for rel in wanted if rel.endswith(".md") and (root / rel).is_file()}

    docs: list[dict] = []
    for rel in sorted(wanted):
        path = root / rel
        exists = path.is_file()
        entry = {
            "path": rel,
            "title": doc_title(root, rel, wanted[rel]) if exists else wanted[rel],
            "folder": str(Path(rel).parent),
            "exists": exists,
            "html": "",
        }
        if exists and rel in embedded:
            text = path.read_text(encoding="utf-8")
            # The view prints the title from the H1, so keeping it in the body too
            # would show it twice.
            text = re.sub(r"\A\s*#\s+[^\n]*\n", "", text)
            entry["html"] = md_to_html(
                text,
                base_dir=str(Path(rel).parent),
                embedded=embedded,
                render_puml_blocks=True,
            )
        docs.append(entry)
    return docs


