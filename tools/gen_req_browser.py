def build_model(root: Path) -> dict:
    records, load_findings = load_records(root)
    if load_findings:
        for f in load_findings:
            print(f"  ! {f['severity']}: {f['where']}: {f['message']}", file=sys.stderr)

    # Reverse links: who derives from me, who verifies me, who allocates to me.
    children: dict[str, list[str]] = {rid: [] for rid in records}
    verifies: dict[str, list[str]] = {rid: [] for rid in records}
    for rid, rec in records.items():
        for parent in rec.get("derived_from", []):
            children.setdefault(parent, []).append(rid)
        for target in rec.get("verified_by", []):
            verifies.setdefault(target, []).append(rid)

    modules: dict[str, dict] = {}
    items: dict[str, dict] = {}

    for rid, rec in sorted(records.items(), key=lambda kv: sort_key(kv[0])):
        rel = rec["_file"]
        folder = str(Path(rel).parent)
        mod = modules.setdefault(
            folder,
            {
                "id": folder,
                "title": MODULE_TITLES.get(folder, folder),
                "process": MODULE_PROCESS.get(folder, ""),
                "path": folder,
                "ids": [],
            },
        )
        mod["ids"].append(rid)

        items[rid] = {
            "id": rid,
            "kind": kind_of(rid),
            "text": rec.get("text", ""),
            "type": rec.get("type", ""),
            "asil": rec.get("asil", ""),
            "status": rec.get("status", ""),
            "source": rec.get("source", ""),
            "rationale": rec.get("rationale", ""),
            "up": rec.get("derived_from", []),
            "down": sorted(children.get(rid, []), key=sort_key),
            "alloc": rec.get("allocated_to", []),
            "vby": rec.get("verified_by", []),
            "verifies": sorted(verifies.get(rid, []), key=sort_key),
            "tags": rec.get("tags", []),
            "file": rel,
            "body": md_to_html(body_of(root / rel)),
        }

