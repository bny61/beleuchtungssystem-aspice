"""Generates visual traceability views from the Requirements-as-Code records.

Two outputs, both from the same graph:

  07_verification/reports/traceability_views.md    scoped Mermaid graphs, rendered by GitHub
  07_verification/reports/trace_explorer.html      self-contained interactive explorer

Reuses the front-matter parser of tools/trace_check.py -- standard library only, no
third-party dependency.

Usage:
    python3 tools/gen_trace_graph.py             # write/update both outputs
    python3 tools/gen_trace_graph.py --check     # check only, exit 1 if stale
    python3 tools/gen_trace_graph.py --root DIR  # different repo root

Exit 0 = up to date or written, 1 = stale (with --check only), 2 = error.

NOTE: produces views used to understand and review the safety case and is therefore --
like trace_check.py and gen_index.py -- a candidate for tool qualification
(ISO 26262-8, Clause 11). See 09_process/plans/tool_qualification.md.
The HTML explorer additionally puts JavaScript between the record and its presentation;
the Mermaid views do not.
"""

