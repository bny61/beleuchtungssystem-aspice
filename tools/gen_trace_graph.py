# ------------------------------------------------------------------------ driver


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=".", help="repo root (default: .)")
    ap.add_argument("--check", action="store_true", help="check only, write nothing")
    args = ap.parse_args()

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"error: root not found: {root}", file=sys.stderr)
        return 2

    records, _ = load_records(root)
    if not records:
        print("No records found - nothing to do.")
        return 0

    edges, downstream, upstream = build_graph(records)
    outputs = {
        root / "07_verification/reports/traceability_views.md":
            build_views(records, edges, downstream, upstream),
        root / "07_verification/reports/trace_explorer.html":
            build_explorer(records, edges, downstream, upstream),
    }

    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path.relative_to(root)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("Stale traceability views:")
            for s in stale:
                print(f"  - {s}")
            print("\nPlease run 'python3 tools/gen_trace_graph.py' and commit the result.")
            return 1
        print(f"Traceability views up to date ({len(records)} records, {len(edges)} links).")
        return 0

    print(f"Traceability views written: {len(records)} records, {len(edges)} links.")
    for path in outputs:
        print(f"  - {path.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
