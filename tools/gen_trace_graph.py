def build_explorer(records: dict, edges: list, downstream: dict, upstream: dict) -> str:
    data = {
        "nodes": [
            {
                "id": rid,
                "kind": kind(rid),
                "asil": str(rec.get("asil", "") or ""),
                "status": str(rec.get("status", "") or ""),
                "type": str(rec.get("type", "") or ""),
                "text": " ".join(str(rec.get("text", "")).split())[:400],
                "file": rec["_file"],
                "level": LEVEL.get(kind(rid), 9),
            }
            for rid, rec in sorted(records.items())
        ],
        "edges": [{"from": a, "to": b, "rel": r} for a, b, r in sorted(edges)],
        "colors": {k: v[0] for k, v in COLOR.items()},
        "strokes": {k: v[1] for k, v in COLOR.items()},
    }
    payload = json.dumps(data, ensure_ascii=False)
    return _EXPLORER_TEMPLATE.replace("/*__DATA__*/", payload)


